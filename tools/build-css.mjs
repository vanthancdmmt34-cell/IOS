// Builds public/css/bundle.min.css from the app stylesheets (same order as the old <link> tags).
//   node tools/build-css.mjs          -> writes the bundle
//   node tools/build-css.mjs --check  -> exits 1 if the bundle is stale (useful in CI / before deploy)
// The source files stay the place to edit; re-run this script after any CSS change.
// Minification is conservative: comments and redundant whitespace are removed, earlier exact
// duplicates of a rule are dropped (the last copy is kept, so the cascade order is unchanged).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CSS_DIR = path.join(ROOT, "public", "css");
export const BUNDLE_SOURCES = ["app.css", "ui-unified.css", "speak.css", "theme.css", "home-learner.css", "handwritten-sync.css", "modern-learn.css", "chibi-ui.css", "chibi-premium.css", "side-menu.css", "app-v4.css", "admin-dash.css", "admin-warm.css"];
const OUT = path.join(CSS_DIR, "bundle.min.css");

// Protect strings and url(...) so that whitespace/comment rules never touch them.
function protect(css) {
  const saved = [];
  let out = "", i = 0;
  const n = css.length;
  while (i < n) {
    const c = css[i];
    if (c === "/" && css[i + 1] === "*") {
      const e = css.indexOf("*/", i + 2);
      i = e < 0 ? n : e + 2;
      out += " ";
      continue;
    }
    if (c === '"' || c === "'") {
      let j = i + 1;
      while (j < n && css[j] !== c) { if (css[j] === "\\") j++; j++; }
      saved.push(css.slice(i, j + 1));
      out += `\u0000${saved.length - 1}\u0000`;
      i = j + 1;
      continue;
    }
    if ((c === "u" || c === "U") && /^url\(/i.test(css.slice(i, i + 4))) {
      // unquoted url(): keep verbatim up to the closing paren
      let j = i + 4;
      while (j < n && /\s/.test(css[j])) j++;
      if (css[j] !== '"' && css[j] !== "'") {
        const e = css.indexOf(")", j);
        const end = e < 0 ? n : e + 1;
        saved.push(css.slice(i, end).replace(/\(\s+/, "(").replace(/\s+\)$/, ")"));
        out += `\u0000${saved.length - 1}\u0000`;
        i = end;
        continue;
      }
    }
    out += c;
    i++;
  }
  return { out, saved };
}
const restore = (css, saved) => css.replace(/\u0000(\d+)\u0000/g, (_, k) => saved[Number(k)]);

// Split a stylesheet into top-level chunks: either "@x ...;" statements or "prelude{...}" blocks.
function topLevelChunks(css) {
  const chunks = [];
  let depth = 0, start = 0;
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (c === "{") depth++;
    else if (c === "}") { depth--; if (depth === 0) { chunks.push(css.slice(start, i + 1)); start = i + 1; } }
    else if (c === ";" && depth === 0) { chunks.push(css.slice(start, i + 1)); start = i + 1; }
  }
  const rest = css.slice(start).trim();
  if (rest) chunks.push(rest);
  return chunks.map((s) => s.trim()).filter(Boolean);
}

export function minifyCss(src) {
  const { out, saved } = protect(src);
  let css = out.replace(/\s+/g, " ");
  // whitespace around block/statement punctuation is never significant
  css = css.replace(/\s*([{};])\s*/g, "$1").replace(/\s*,\s*/g, ",");
  // innermost blocks are declaration lists: "prop : value" -> "prop:value", drop the last ";"
  // (custom properties with an empty value keep one space: "--x: ;" must not become "--x:;")
  css = css.replace(/\{([^{}]*)\}/g, (_, body) => "{" + body.split(";").map((d) => {
    if (/^--[-\w]+\s*:\s*$/.test(d)) return d.replace(/\s*:\s*$/, ": ");
    return d.replace(/^([-\w]+)\s*:\s*/, "$1:").replace(/\s*!important$/i, "!important")
      // 0.5 -> .5 (only when the 0 starts a number), #aabbcc -> #abc
      .replace(/(^|[\s:(,+*/-])0\.(\d)/g, "$1.$2")
      .replace(/#([0-9a-fA-F])\1([0-9a-fA-F])\2([0-9a-fA-F])\3(?![0-9a-fA-F])/g, "#$1$2$3");
  }).join(";").replace(/;+$/, "") + "}");
  css = css.replace(/;;+/g, ";").replace(/\{;/g, "{").trim();
  // drop empty rules (not @font-face etc. with content)
  css = css.replace(/(^|[{}])[^{}@;]+\{\}/g, "$1");
  // Không khử trùng lặp theo khối: việc tách khối theo dấu ngoặc làm rơi khai báo khi CSS nguồn có lỗi
  // (đã gặp: một dấu } thừa trong chibi-ui.css làm mất flex-direction của nhiều quy tắc).
  // Giữ nguyên thứ tự khai báo để cascade đúng như file nguồn.
  return restore(css, saved);
}

export function buildBundle() {
  const parts = BUNDLE_SOURCES.map((f) => fs.readFileSync(path.join(CSS_DIR, f), "utf8"));
  // @import / @charset must stay at the top of the merged file
  const imports = [];
  const body = parts.map((p) => p.replace(/@import\s+[^;]+;/g, (m) => { imports.push(m); return ""; }).replace(/@charset\s+[^;]+;/gi, "")).join("\n");
  const header = `/* bundle.min.css: generated by tools/build-css.mjs from ${BUNDLE_SOURCES.join(", ")}. Do not edit. */\n`;
  return header + minifyCss(imports.join("\n") + "\n" + body) + "\n";
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const built = buildBundle();
  if (process.argv.includes("--check")) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (cur !== built) { console.error("bundle.min.css is stale: run node tools/build-css.mjs"); process.exit(1); }
    console.log("bundle.min.css is up to date");
  } else {
    fs.writeFileSync(OUT, built);
    const srcKb = BUNDLE_SOURCES.reduce((s, f) => s + fs.statSync(path.join(CSS_DIR, f)).size, 0) / 1024;
    console.log(`bundle.min.css: ${(built.length / 1024).toFixed(1)} KB (sources ${srcKb.toFixed(1)} KB)`);
  }
}
